// Признак «страница открыта с этой же машины» — в самом источнике.
//
// Ядро вычисляет его в браузере один раз, при сборке объекта соединения:
//
//     isLoopback: pageLocation === void 0 || isLoopbackHostname(pageLocation.hostname)
//
// Дальше это обычное свойство обычного объекта, и подменить его на странице
// можно — плагин так и делает. Но подмена успевает не везде: разделы настроек
// привязываются в момент своего apply, и тот, кто привязался раньше нашего
// клиентского кода, уже запомнил «нет». Вкладка «Модели» — как раз такой
// случай: она читает раздел с провайдерами до нас, получает пустое хранилище
// вместо файла, и девять заведённых провайдеров исчезают из списка вместе с
// возможностью их выбрать.
//
// Гонку не выиграть перестановкой: порядок загрузки задаёт не плагин. Поэтому
// значение правится там, где его больше никто не обгонит — в самом файле,
// пока он идёт через мост. Одна строка, одно вхождение, остальной файл
// нетронут.
//
// Настоящее значение при этом не теряется: клиентская часть плагина отдаёт его
// тем, кому оно действительно нужно — выдаче результатов работы, где флаг
// решает, открывать ли путь на своей машине или на серверной.

/** Путь, по которому ядро отдаёт сборку с этим вычислением. */
export const CONNECTION_BUNDLE = '/plugins/@deepseek-ai/dsh-client-connection/client.js'

/** Ровно то выражение, которое считает признак. */
const COMPUTED = 'isLoopback: pageLocation === void 0 || isLoopbackHostname(pageLocation.hostname),'

/** Чем его заменяем. */
const ALWAYS = 'isLoopback: true,'

/** Тот ли это запрос: путь сверяем без строки запроса — там висит ?rev=... */
export function isConnectionBundle(url) {
  const path = String(url ?? '').split('?')[0]
  return path === CONNECTION_BUNDLE
}

/**
 * Заменить вычисление признака на «да».
 *
 * @param source текст сборки
 * @returns `{ source, changed }` — исходник и признак того, что замена нашлась
 */
export function forceLoopback(source) {
  const text = String(source)
  if (!text.includes(COMPUTED)) return { source: text, changed: false }
  return { source: text.replace(COMPUTED, ALWAYS), changed: true }
}
